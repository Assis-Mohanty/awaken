// Converts react-native-body-highlighter (MIT) male front/back assets into a Kotlin source file.
// Data is extracted with regexes (never evaluated). Paths are normalised with svgpath: absolute commands, arcs turned
// into cubics, the back view shifted to x = 0, rounded to 2 decimals.
// usage: node convert.js <repoDir> <outFile>
const fs = require('fs');
const path = require('path');
const svgpath = require('svgpath');

const [repo, out] = process.argv.slice(2);
const read = (p) => fs.readFileSync(path.join(repo, p), 'utf8');

function regions(src, dx) {
  const parts = src.split(/slug:\s*"/).slice(1);
  return parts.map((part) => {
    const slug = part.slice(0, part.indexOf('"'));
    const paths = [...part.matchAll(/"(M[^"]+)"/g)].map((m) => norm(m[1], dx));
    return { slug, paths };
  });
}

function norm(d, dx) {
  return svgpath(d).translate(-dx, 0).abs().unarc().round(2).toString();
}

function outline(side) {
  const wrapper = read('components/SvgMaleWrapper.tsx');
  const re = new RegExp('d="([^"]+)"\\s*accessible=\\{true\\}\\s*accessibilityLabel="male-body-outline-' + side + '"');
  const m = wrapper.match(re);
  if (!m) throw new Error('no outline for ' + side);
  return norm(m[1], side === 'back' ? 724 : 0);
}

const front = regions(read('assets/bodyFront.ts'), 0);
const back = regions(read('assets/bodyBack.ts'), 724);

const kt = (list) => list.map((r) =>
  `        Region("${r.slug}", listOf(\n${r.paths.map((p) => `            "${p}",`).join('\n')}\n        )),`).join('\n');

const src = `package com.assismohanty.awaken.core.designsystem.body

/*
 * GENERATED by tools/body/convert.js from react-native-body-highlighter (male front/back, assets/bodyFront.ts,
 * assets/bodyBack.ts, components/SvgMaleWrapper.tsx). Do not edit by hand; re-run the script.
 *
 * MIT License, Copyright (c) 2022 ELABBASSI Hicham. Full text: assets/licenses/MIT_react-native-body-highlighter.txt.
 *
 * Paths are absolute, arcs converted to cubics, back view shifted to x = 0, in a ${724} × ${1448} viewport.
 */

internal object BodyPaths {
    const val WIDTH = 724f
    const val HEIGHT = 1448f

    /** One source region: its slug and the SVG path data of its left and right parts. */
    class Region(val slug: String, val paths: List<String>)

    const val FRONT_OUTLINE = "${outline('front')}"

    const val BACK_OUTLINE = "${outline('back')}"

    val front: List<Region> = listOf(
${kt(front)}
    )

    val back: List<Region> = listOf(
${kt(back)}
    )
}
`;
fs.writeFileSync(out, src);
