/** A stored recap ready to show (GD §14.6): the snapshot plus the period's insight, re-derived on open. */
data class RecapModel(val payload: RecapPayload, val insight: Insight?)

/** One row of the RECAPS list on Status. */
data class RecapEntry(val periodKey: String, val yearly: Boolean, val start: LocalDate) {
    companion object {
        /** "M:2026-10" or "Y:2026"; null for a key this build doesn't know. */
        fun of(periodKey: String): RecapEntry? = when {
            periodKey.startsWith("M:") -> periodKey.removePrefix("M:").let { runCatching { YearMonth.parse(it) }.getOrNull() }
                ?.let { RecapEntry(periodKey, yearly = false, start = it.atDay(1)) }
            periodKey.startsWith("Y:") -> periodKey.removePrefix("Y:").toIntOrNull()
                ?.let { RecapEntry(periodKey, yearly = true, start = LocalDate.of(it, 1, 1)) }
            else -> null
        }
    }
}

/**
 * Generates the recaps due today (GD §14.6), yearly first. Idempotent on the period key: an existing recap is never
 * rebuilt. Returns the keys generated by this call, so the first one can be auto-opened once.
 */
class GenerateRecapsUseCase @Inject constructor(
    private val hunterDao: HunterDao,
    private val recapDao: RecapDao,
    private val insightDao: InsightDao,
    private val clock: Clock,
) {
    suspend operator fun invoke(): List<String> {
        val profile = hunterDao.getProfile() ?: return emptyList()
        val today = clock.gameDate(profile.dayStartHour)
        val existing = recapDao.keys().toSet()
        // The engine decides; the finalized-day counts are read up front because its predicate is not suspending.
        val counts = listOfNotNull(RecapRules.previousYear(today), RecapRules.previousMonth(today))
            .associate { it.key to recapDao.finalizedDays(it.start, it.end) }
        val due = RecapRules.due(today, existing) { counts[it.key] ?: 0 }
        return due.mapNotNull { period ->
            val payload = RecapRules.build(input(profile, period))
            val inserted = recapDao.insert(
                RecapEntity(
                    periodKey = period.key,
                    generatedAt = clock.now(),
                    payloadVersion = RecapRules.PAYLOAD_VERSION,
                    payloadJson = json.encodeToString(RecapPayload.serializer(), payload),
                ),
            )
            period.key.takeIf { inserted != -1L }
        }
    }

    private suspend fun input(profile: HunterProfileEntity, period: RecapPeriod): RecapInput {
        val zone = clock.zone()
        return RecapInput(
            period = period,
            questsCompleted = insightDao.completionCounts(period.start, period.end).sumOf { it.total }.toInt(),
            clearedGateSeconds = recapDao.clearedGateSeconds(period.start, period.end),
            outcomesThroughEnd = insightDao.outcomes(profile.firstGameDate, period.end).map { it.gameDate to it.outcome },
            statXpBefore = recapDao.statXpBefore(period.start).byStat(),
            statXpGained = recapDao.statXpBetween(period.start, period.end).byStat(),
            xpBefore = recapDao.xpBefore(period.start),
            xpGained = recapDao.xpBetween(period.start, period.end),
            health = if (profile.healthEnabled) {
                insightDao.healthDays(period.start, period.end).map { RecapHealthDay(it.distanceMeters, it.steps, it.sleepMinutes) }
            } else {
                emptyList()
            },
            achievementsEarned = recapDao.achievementsBetween(
                GameDay.startOf(period.start, zone, profile.dayStartHour),
                GameDay.startOf(period.end.plusDays(1), zone, profile.dayStartHour),
            ),
        )
    }

    private fun List<StatTotal>.byStat(): Map<Stat, Long> {
        val totals = associate { it.stat to it.total }
        return Stat.entries.associateWith { totals[it.name] ?: 0L }
    }
}

/** Opens a stored recap; null if it doesn't exist or its snapshot can't be read (it is only a cache). */
class LoadRecapUseCase @Inject constructor(
    private val hunterDao: HunterDao,
    private val recapDao: RecapDao,
    private val loadInsights: LoadInsightsUseCase,
) {
    suspend operator fun invoke(periodKey: String): RecapModel? {
        val profile = hunterDao.getProfile() ?: return null
        val entity = recapDao.get(periodKey) ?: return null
        val payload = try {
            json.decodeFromString(RecapPayload.serializer(), entity.payloadJson)
        } catch (e: IllegalArgumentException) {
            Timber.e(e, "Recap %s payload unreadable", periodKey)
            return null
        }
        val start = LocalDate.parse(payload.start)
        val end = LocalDate.parse(payload.end)
        val days = ChronoUnit.DAYS.between(start, end) + 1
        val insight = InsightEngine.evaluate(loadInsights.history(profile, start, end), end, windowDays = days).insights.firstOrNull()
        return RecapModel(payload, insight)
    }
}

private val json = Json { ignoreUnknownKeys = true }
